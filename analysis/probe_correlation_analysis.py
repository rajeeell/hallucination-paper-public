"""Probe-correlation analysis: do memorization-PPL and parametric-PPL predict
the §5.5/§5.6 perplexity-reversal at k=1?

Inputs (all under `analysis/`):
  - memorization_results/memorization/<model>/<dataset>/memprobe_n200.json
      (gold-answer NLL under no-context, generated by tools/modal_memorization_probe.py)
  - parametric_results/parametric/<model>/<dataset>/paramprobe_n100.json
      (model's own no-context generation + PPL, generated by tools/modal_parametric_probe.py)
  - vary_k_labeled_claude-opus-4-6/vary_k/<model>/<dataset>/vary_k_n100_k1.json
      (labeled k=1 generations under seed=42 protocol)

What this script computes
-------------------------
1. Cell-level Spearman correlation across 8 cells: log median mem_ppl /
   log median param_ppl vs k=1 perplexity AUROC.
2. Bootstrap 95% CIs on each Spearman (B = 10,000).
3. Item-level per-cell AUROC for mem_ppl, param_ppl, and combined.
4. Two-panel scatter figure: log median mem_ppl vs AUROC, log median
   param_ppl vs AUROC, one point per cell, colored by model.

Outputs
-------
  - analysis/results/probe_correlation_table.csv (cell-level)
  - analysis/results/probe_correlation_item_level.csv (within-cell AUROCs)
  - analysis/figures/probe_correlation_scatter.{pdf,png}
"""

from __future__ import annotations

import json
import os
import pathlib

import numpy as np
import pandas as pd
from scipy.stats import spearmanr
from sklearn.metrics import roc_auc_score
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline


REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS_DIR = REPO_ROOT / "analysis" / "results"
FIG_DIR = REPO_ROOT / "analysis" / "figures"
RESULTS_DIR.mkdir(parents=True, exist_ok=True)
FIG_DIR.mkdir(parents=True, exist_ok=True)

MEM_DIR = REPO_ROOT / "analysis" / "memorization_results" / "memorization"
PARAM_DIR = REPO_ROOT / "analysis" / "parametric_results" / "parametric"
LABEL_DIR = REPO_ROOT / "analysis" / "vary_k_labeled_claude-opus-4-6" / "vary_k"


CELLS = [
    ("Phi-3-mini-4k-instruct",   "squad",  "microsoft_Phi-3-mini-4k-instruct/squad",  "Phi-3-mini"),
    ("Phi-3-mini-4k-instruct",   "hotpot", "microsoft_Phi-3-mini-4k-instruct/hotpot", "Phi-3-mini"),
    ("gemma-3-4b-it",            "squad",  "google_gemma-3-4b-it/squad",              "Gemma-3-4B"),
    ("gemma-3-4b-it",            "hotpot", "google_gemma-3-4b-it/hotpot",             "Gemma-3-4B"),
    ("Llama-3.1-8B-Instruct",    "squad",  "meta-llama_Llama-3.1-8B-Instruct/squad",  "Llama-3.1-8B"),
    ("Llama-3.1-8B-Instruct",    "hotpot", "meta-llama_Llama-3.1-8B-Instruct/hotpot", "Llama-3.1-8B"),
    ("Qwen2.5-14B-Instruct",     "squad",  "Qwen_Qwen2.5-14B-Instruct/squad",         "Qwen-2.5-14B"),
    ("Qwen2.5-14B-Instruct",     "hotpot", "Qwen_Qwen2.5-14B-Instruct/hotpot",        "Qwen-2.5-14B"),
]


def load_cell(subdir: str) -> dict:
    labeled = json.loads((LABEL_DIR / subdir / "vary_k_n100_k1.json").read_text())
    mems = json.loads((MEM_DIR / subdir / "memprobe_n200.json").read_text())["records"]
    params = json.loads((PARAM_DIR / subdir / "paramprobe_n100.json").read_text())["records"]
    m_by_q = {m["question"]: m for m in mems}
    p_by_q = {p["question"]: p for p in params}
    matched = []
    for lab in labeled:
        q = lab["question"]
        m, p = m_by_q.get(q), p_by_q.get(q)
        if not m or not p:
            continue
        if not np.isfinite(m.get("mem_ppl") or np.nan) or (m["mem_ppl"] or 0) <= 0:
            continue
        if not np.isfinite(p.get("parametric_perplexity") or np.nan):
            continue
        matched.append({
            "k1_ppl": lab["perplexity"],
            "mem_ppl": m["mem_ppl"],
            "param_ppl": p["parametric_perplexity"],
            "hall": lab["hallucinated"],
        })
    return matched


def lr_cv_auc(X: np.ndarray, y: np.ndarray, seed: int = 42) -> float:
    if len(np.unique(y)) < 2:
        return float("nan")
    skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=seed)
    scores = np.zeros(len(y))
    for tr, te in skf.split(X, y):
        pipe = Pipeline([("sc", StandardScaler()),
                         ("lr", LogisticRegression(max_iter=1000))])
        pipe.fit(X[tr], y[tr])
        scores[te] = pipe.predict_proba(X[te])[:, 1]
    return float(roc_auc_score(y, scores))


def boot_spearman(xs: np.ndarray, ys: np.ndarray, B: int = 10000, seed: int = 42) -> tuple:
    rng = np.random.default_rng(seed)
    n = len(xs)
    rhos = np.full(B, np.nan)
    for b in range(B):
        idx = rng.choice(n, n, replace=True)
        if len(set(xs[idx])) < 2 or len(set(ys[idx])) < 2:
            continue
        rhos[b], _ = spearmanr(xs[idx], ys[idx])
    rhos = rhos[np.isfinite(rhos)]
    lo, hi = np.percentile(rhos, [2.5, 97.5])
    return float(lo), float(hi), float((rhos > 0).mean())


def main() -> None:
    cell_rows = []
    for model_full, dataset, subdir, model_short in CELLS:
        matched = load_cell(subdir)
        if len(matched) < 30:
            print(f"[skip] {model_full}/{dataset}: only {len(matched)} matched")
            continue
        k1 = np.log(np.array([r["k1_ppl"] for r in matched]))
        mem = np.log(np.array([r["mem_ppl"] for r in matched]))
        param = np.log(np.array([r["param_ppl"] for r in matched]))
        y = np.array([r["hall"] for r in matched])

        auc_p = roc_auc_score(y, k1) if len(np.unique(y)) > 1 else float("nan")
        auc_m = roc_auc_score(y, mem) if len(np.unique(y)) > 1 else float("nan")
        auc_param = roc_auc_score(y, param) if len(np.unique(y)) > 1 else float("nan")
        auc_pm = lr_cv_auc(np.c_[k1, mem], y)
        auc_pp = lr_cv_auc(np.c_[k1, param], y)
        auc_pmp = lr_cv_auc(np.c_[k1, mem, param], y)

        cell_rows.append({
            "model_full": model_full,
            "model": model_short,
            "dataset": dataset,
            "cell": f"{model_short}/{dataset}",
            "n_matched": len(matched),
            "pos_rate": float(y.mean()),
            "k1_perplexity_AUROC": auc_p,
            "log_med_mem_ppl": float(np.median(mem)),
            "log_med_param_ppl": float(np.median(param)),
            "median_mem_ppl": float(np.exp(np.median(mem))),
            "median_param_ppl": float(np.exp(np.median(param))),
            "item_AUC_mem_alone": auc_m,
            "item_AUC_param_alone": auc_param,
            "item_AUC_PPL+mem": auc_pm,
            "item_AUC_PPL+param": auc_pp,
            "item_AUC_PPL+mem+param": auc_pmp,
        })

    df = pd.DataFrame(cell_rows)
    df.to_csv(RESULTS_DIR / "probe_correlation_table.csv", index=False)
    print(f"wrote {RESULTS_DIR/'probe_correlation_table.csv'}")

    print("\n--- Cell-level table (k=1 vary_k seed=42 protocol, n=8) ---")
    print(df[["cell", "n_matched", "pos_rate", "k1_perplexity_AUROC",
              "median_mem_ppl", "median_param_ppl",
              "item_AUC_mem_alone", "item_AUC_param_alone",
              "item_AUC_PPL+param"]].to_string(index=False))

    aurocs = df["k1_perplexity_AUROC"].to_numpy()
    xs_mem = df["log_med_mem_ppl"].to_numpy()
    xs_param = df["log_med_param_ppl"].to_numpy()

    sp_m, p_m = spearmanr(xs_mem, aurocs)
    sp_p, p_p = spearmanr(xs_param, aurocs)
    lo_m, hi_m, frac_pos_m = boot_spearman(xs_mem, aurocs)
    lo_p, hi_p, frac_pos_p = boot_spearman(xs_param, aurocs)

    print("\n--- Cell-level Spearman correlations ---")
    print(f"log median mem_ppl   vs k=1 AUROC: ρ = {sp_m:>+.3f}  asymptotic p = {p_m:.4f}")
    print(f"                                  bootstrap 95% CI = [{lo_m:>+.3f}, {hi_m:>+.3f}]  frac > 0 = {frac_pos_m:.3f}")
    print(f"log median param_ppl vs k=1 AUROC: ρ = {sp_p:>+.3f}  asymptotic p = {p_p:.4f}")
    print(f"                                   bootstrap 95% CI = [{lo_p:>+.3f}, {hi_p:>+.3f}]  frac > 0 = {frac_pos_p:.3f}")

    # Persist the correlations
    with open(RESULTS_DIR / "probe_correlation_spearman.json", "w") as f:
        json.dump({
            "n_cells": len(df),
            "log_med_mem_ppl_vs_AUROC": {
                "rho": sp_m, "p_asymptotic": p_m,
                "boot_ci_lo": lo_m, "boot_ci_hi": hi_m,
                "frac_positive": frac_pos_m,
            },
            "log_med_param_ppl_vs_AUROC": {
                "rho": sp_p, "p_asymptotic": p_p,
                "boot_ci_lo": lo_p, "boot_ci_hi": hi_p,
                "frac_positive": frac_pos_p,
            },
        }, f, indent=2)
    print(f"wrote {RESULTS_DIR/'probe_correlation_spearman.json'}")

    # --- figure: two panels, scatter ---
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    model_colors = {
        "Phi-3-mini":   "#4477AA",
        "Gemma-3-4B":   "#EE6677",
        "Llama-3.1-8B": "#228833",
        "Qwen-2.5-14B": "#CCBB44",
    }
    dataset_markers = {"squad": "o", "hotpot": "s"}

    fig, axes = plt.subplots(1, 2, figsize=(11, 4.5), sharey=True)
    for ax, (x_col, x_label, rho) in zip(
        axes,
        [("log_med_mem_ppl", r"$\log$ median memorization PPL (no-context, gold)", sp_m),
         ("log_med_param_ppl", r"$\log$ median parametric PPL (no-context, own)", sp_p)],
    ):
        for _, row in df.iterrows():
            ax.scatter(
                row[x_col],
                row["k1_perplexity_AUROC"],
                marker=dataset_markers[row["dataset"]],
                color=model_colors[row["model"]],
                s=90, edgecolors="black", linewidths=0.7, zorder=3,
            )
            ax.annotate(
                row["cell"], (row[x_col], row["k1_perplexity_AUROC"]),
                fontsize=7, xytext=(4, 4), textcoords="offset points",
            )
        ax.axhline(0.5, color="grey", linestyle=":", linewidth=0.8, alpha=0.6)
        ax.set_xlabel(x_label)
        ax.set_ylabel("k=1 perplexity AUROC")
        ax.set_title(f"Spearman ρ = {rho:>+.2f}")
        ax.grid(alpha=0.3)

    # legend
    from matplotlib.lines import Line2D
    handles = (
        [Line2D([0], [0], marker="o", color="w", markerfacecolor=c, markeredgecolor="black",
                markersize=8, label=name) for name, c in model_colors.items()]
        + [Line2D([0], [0], marker=m, color="w", markerfacecolor="grey", markeredgecolor="black",
                markersize=8, label=f"dataset = {d}") for d, m in dataset_markers.items()]
    )
    axes[1].legend(handles=handles, loc="lower right", frameon=True, fontsize=7)

    fig.suptitle("Cell-level: probe medians vs k=1 perplexity AUROC (8 cells, seed=42 protocol)")
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    fig.savefig(FIG_DIR / "probe_correlation_scatter.pdf", bbox_inches="tight")
    fig.savefig(FIG_DIR / "probe_correlation_scatter.png", dpi=150, bbox_inches="tight")
    print(f"wrote {FIG_DIR/'probe_correlation_scatter.pdf'}")
    print(f"wrote {FIG_DIR/'probe_correlation_scatter.png'}")


if __name__ == "__main__":
    main()
